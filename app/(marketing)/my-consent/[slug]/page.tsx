import type { Metadata } from "next";
import { Clock, ShieldCheck } from "lucide-react";
import { getConsentBySlug } from "@/lib/queries/consent";
import { CONSENT_TTL_MS } from "@/lib/files/consent-upload";
import { ConsentForm } from "./consent-form";

export const metadata: Metadata = { title: "Consultation Consent" };

/** One day in ms — only used to state the window in the patient's units. */
const DAY_MS = 24 * 60 * 60 * 1000;

export default async function ConsentPage({
  params,
}: {
  params: Promise<{ slug: string }>;
}) {
  const { slug } = await params;
  const consent = await getConsentBySlug(slug);

  // getConsentBySlug returns null for a slug that never existed, for one that
  // was already answered, and for one past its retention window — the three
  // are deliberately indistinguishable, so all three get this state rather
  // than an empty or broken page (audit M5 / FR-019).
  if (!consent) {
    return (
      <section className="flex min-h-screen items-center justify-center bg-gradient-to-br from-brand-50 via-accent-50/40 to-brand-50 px-5 py-24">
        <div className="w-full max-w-lg">
          <div className="rounded-3xl border border-brand-900/10 bg-white p-8 shadow-float">
            <div className="flex items-center gap-3">
              <div className="flex h-12 w-12 items-center justify-center rounded-2xl bg-brand-700 text-white">
                <Clock className="h-6 w-6" />
              </div>
              <div>
                <h1 className="font-display text-xl font-extrabold text-ink">
                  Consent link no longer valid
                </h1>
                <p className="text-sm text-ink-muted">
                  This request expired or was already answered.
                </p>
              </div>
            </div>

            <p className="mt-6 text-sm leading-relaxed text-ink-muted">
              Consent links stay valid for {Math.round(CONSENT_TTL_MS / DAY_MS)} days after the
              clinic created them. If you still need to respond, please contact your clinic and
              ask for a new consent request — no response is required in the meantime.
            </p>
          </div>

          <p className="mt-6 text-center text-xs text-ink-muted">
            Secured by SkoraCares · This request was generated by your healthcare provider.
          </p>
        </div>
      </section>
    );
  }

  return (
    <section className="flex min-h-screen items-center justify-center bg-gradient-to-br from-brand-50 via-accent-50/40 to-brand-50 px-5 py-24">
      <div className="w-full max-w-lg">
        <div className="rounded-3xl border border-brand-900/10 bg-white p-8 shadow-float">
          <div className="flex items-center gap-3">
            <div className="flex h-12 w-12 items-center justify-center rounded-2xl bg-brand-700 text-white">
              <ShieldCheck className="h-6 w-6" />
            </div>
            <div>
              <h1 className="font-display text-xl font-extrabold text-ink">Consultation consent</h1>
              <p className="text-sm text-ink-muted">Please review and respond below.</p>
            </div>
          </div>

          <div className="mt-7 space-y-4 rounded-2xl bg-surface p-5 text-sm">
            <div className="flex items-center justify-between">
              <span className="text-ink-muted">Doctor</span>
              <span className="font-semibold text-ink">{consent.doctorName}</span>
            </div>
            {consent.doctorQualification && (
              <div className="flex items-center justify-between">
                <span className="text-ink-muted">Qualification</span>
                <span className="font-semibold text-ink">{consent.doctorQualification}</span>
              </div>
            )}
            <div className="flex items-center justify-between">
              <span className="text-ink-muted">Patient</span>
              <span className="font-semibold text-ink">You</span>
            </div>
            {consent.appointmentDate && (
              <div className="flex items-center justify-between">
                <span className="text-ink-muted">Appointment</span>
                <span className="font-semibold text-ink">
                  {new Date(consent.appointmentDate).toLocaleDateString("en-IN", {
                    day: "numeric",
                    month: "long",
                    year: "numeric",
                  })}
                  {consent.appointmentTime ? ` at ${consent.appointmentTime}` : ""}
                </span>
              </div>
            )}
          </div>

          <p className="mt-6 text-sm leading-relaxed text-ink-muted">
            I understand and consent to the medical consultation with the doctor named above,
            including any recommended examinations, diagnostic tests and treatments. I confirm
            that the information I have provided is accurate to the best of my knowledge.
          </p>

          <ConsentForm slug={consent.slug} />
        </div>

        <p className="mt-6 text-center text-xs text-ink-muted">
          Secured by SkoraCares · This request was generated by your healthcare provider.
        </p>
      </div>
    </section>
  );
}
